    fun byTopic(topicId: String): List<QuizQuestion> = all.filter { it.topicId == topicId }

    fun levelUpQuestions(level: Level): List<QuizQuestion> {
        val topics = GrammarCurriculum.topicsByLevel[level].orEmpty()
        val hard = topics.flatMap { byTopic(it.id).takeLast(2) }
        return hard.shuffled().take(8)
    }
